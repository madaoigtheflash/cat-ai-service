const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { createState, transition, applyCommand, readServer, project, OWNER } = require('../utils/cato-sync-contract')
const clone = value => JSON.parse(JSON.stringify(value))
const act = (state, type, deviceId = 'a', rest = {}) => transition(state, { type, deviceId, ...rest })
const client = (state, device = 'a') => state.clients.find(item => item.id === device)
const firstId = state => Object.keys(state.server.records)[0]
function sharedTask() {
  let state = act(createState(), 'create', 'a', { title: '记录饮水情况' })
  return act(state, 'sync', 'b')
}
function conflicted() {
  let state = sharedTask()
  const recordId = firstId(state)
  state = act(state, 'toggleOnline', 'b')
  state = act(state, 'edit', 'b', { recordId, title: 'B 的本地名称' })
  state = act(state, 'complete', 'b', { recordId, completed: true })
  state = act(state, 'edit', 'a', { recordId, title: 'A 的权威端名称' })
  return act(state, 'toggleOnline', 'b')
}
function harness(t) {
  const values = {}
  const driver = {
    failWrite: false, modal: null,
    getStorageSync: key => values[key],
    setStorageSync(key, value) { if (this.failWrite) throw Error('quota'); values[key] = clone(value) },
    showModal(options) { this.modal = options }
  }
  let definition
  global.wx = driver
  global.Page = value => { definition = value }
  const file = require.resolve('../pages/cato-sync-contract/index')
  delete require.cache[file]
  require(file)
  function open() {
    const page = { ...definition, data: clone(definition.data), setData(patch) {
      for (const [key, value] of Object.entries(patch)) {
        const parts = key.split('.')
        let at = this.data
        for (const part of parts.slice(0, -1)) at = at[part]
        at[parts.at(-1)] = clone(value)
      }
    } }
    page.onLoad()
    return page
  }
  t.after(() => { delete global.wx; delete global.Page; delete require.cache[file] })
  return { driver, values, page: open(), open }
}

