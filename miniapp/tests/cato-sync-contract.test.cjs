test('create, edit, complete, undo and delete increment versions without mutating input', () => {
  const initial = createState()
  let state = act(initial, 'create', 'a', { title: '  饮水记录  ' })
  const recordId = firstId(state)
  assert.equal(state.server.records[recordId].title, '饮水记录')
  assert.deepEqual(initial, createState())
  state = act(state, 'edit', 'a', { recordId, title: '晚间饮水记录' })
  state = act(state, 'complete', 'a', { recordId, completed: true })
  state = act(state, 'complete', 'a', { recordId, completed: false })
  state = act(state, 'delete', 'a', { recordId })
  assert.deepEqual(state.server.records[recordId], { id: recordId, ownerId: OWNER, version: 5, title: '', completed: false, deleted: true })
  assert.equal(state.server.revision, 5)
  assert.equal(Object.keys(state.server.receipts).length, 5)
})
