test('offline commands chain expected versions and reconnect applies in order', () => {
  let state = act(createState(), 'toggleOnline')
  state = act(state, 'create', 'a', { title: '离线新建' })
  const recordId = Object.keys(client(state).records)[0]
  state = act(state, 'edit', 'a', { recordId, title: '离线修改' })
  state = act(state, 'complete', 'a', { recordId, completed: true })
  assert.deepEqual(client(state).queue.map(command => command.expectedVersion), [0, 1, 2])
  assert.equal(new Set(client(state).queue.map(command => command.id)).size, 3)
  assert.equal(state.server.revision, 0)
  state = act(state, 'toggleOnline')
  assert.equal(state.server.records[recordId].version, 3)
  assert.equal(state.server.records[recordId].completed, true)
  assert.equal(client(state).queue.length, 0)
})
