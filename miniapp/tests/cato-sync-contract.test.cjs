test('stale version exposes conflict snapshots, keeps queue, and blocks silent writes', () => {
  const state = conflicted()
  const before = clone(state)
  const b = client(state, 'b')
  assert.equal(b.conflict.code, 'CONFLICT')
  assert.equal(b.conflict.local.version, 3)
  assert.equal(b.conflict.remote.version, 2)
  assert.equal(b.queue.length, 2)
  assert.equal(state.server.revision, 2)
  assert.throws(() => act(state, 'create', 'b', { title: '不能偷偷越过冲突' }), /先明确解决/)
  assert.deepEqual(state, before)
})
