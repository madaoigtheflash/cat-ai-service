test('page persistence failure preserves in-memory and saved state, and retries once', t => {
  const h = harness(t)
  h.page.commit({ type: 'create', deviceId: 'a', title: '已保存' })
  const before = clone(h.page._state)
  const storedBefore = clone(h.values)
  h.driver.failWrite = true
  assert.equal(h.page.commit({ type: 'edit', deviceId: 'a', recordId: firstId(before), title: '尚未保存' }), false)
  assert.deepEqual(h.page._state, before)
  assert.deepEqual(h.values, storedBefore)
  assert.equal(h.page.data.retryAvailable, true)
  assert.equal(h.open()._state.server.revision, 1)
  h.driver.failWrite = false
  h.page.retrySave()
  assert.equal(h.page._state.server.revision, 2)
  assert.equal(h.page.data.retryAvailable, false)
  assert.equal(h.open()._state.server.records[firstId(before)].title, '尚未保存')
  assert.deepEqual(Object.keys(h.values), ['catai_cato_lab_v1:sync-contract:state'])
})
test('failed reconnect persistence retains offline queue; retry commits authority only once', t => {
  const h = harness(t)
  h.page.commit({ type: 'toggleOnline', deviceId: 'a' })
  h.page.commit({ type: 'create', deviceId: 'a', title: '离线保存' })
  h.page.armFailure()
  assert.equal(h.page.commit({ type: 'toggleOnline', deviceId: 'a' }), false)
  assert.equal(h.page._state.server.revision, 0)
  assert.equal(client(h.page._state).queue.length, 1)
  assert.equal(client(h.page._state).online, false)
  h.page.retrySave()
  assert.equal(h.page._state.server.revision, 1)
  assert.equal(client(h.page._state).queue.length, 0)
  assert.equal(h.open()._state.server.revision, 1)
})
